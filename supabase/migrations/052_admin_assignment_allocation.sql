-- intentionally independent of instrument-format and N/A scoring changes.

ALTER TABLE public.observation_teacher_assignments
  DROP CONSTRAINT observation_teacher_assignments_source_check;
ALTER TABLE public.observation_teacher_assignments
  ADD CONSTRAINT observation_teacher_assignments_source_check
  CHECK (source IN ('admin', 'legacy_backfill', 'automatic_allocation'));

CREATE TABLE public.observation_allocation_preferences (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuatrimestre_id INTEGER NOT NULL REFERENCES public.cuatrimestres(id),
  evaluator_id UUID NOT NULL REFERENCES public.usuarios(id),
  included BOOLEAN NOT NULL DEFAULT true,
  target_teacher_count INTEGER CHECK (target_teacher_count IS NULL OR target_teacher_count BETWEEN 0 AND 10000),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by UUID NOT NULL REFERENCES public.usuarios(id),
  UNIQUE (cuatrimestre_id, evaluator_id)
);

CREATE TABLE public.observation_allocation_previews (
  id UUID PRIMARY KEY DEFAULT extensions.gen_random_uuid(),
  cuatrimestre_id INTEGER NOT NULL REFERENCES public.cuatrimestres(id),
  seed UUID NOT NULL,
  fingerprint UUID NOT NULL DEFAULT extensions.gen_random_uuid(),
  created_by UUID NOT NULL REFERENCES public.usuarios(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  proposal JSONB NOT NULL,
  summary JSONB NOT NULL,
  confirmed_at TIMESTAMPTZ,
  confirmed_by UUID REFERENCES public.usuarios(id),
  CHECK (expires_at > created_at),
  CHECK ((confirmed_at IS NULL) = (confirmed_by IS NULL))
);

CREATE TABLE public.observation_allocation_runs (
  id UUID PRIMARY KEY DEFAULT extensions.gen_random_uuid(),
  preview_id UUID NOT NULL UNIQUE REFERENCES public.observation_allocation_previews(id),
  cuatrimestre_id INTEGER NOT NULL REFERENCES public.cuatrimestres(id),
  seed UUID NOT NULL,
  initiated_by UUID NOT NULL REFERENCES public.usuarios(id),
  initiated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  counts JSONB NOT NULL
);

CREATE INDEX observation_allocation_preferences_cycle_idx
  ON public.observation_allocation_preferences (cuatrimestre_id, included);
CREATE INDEX observation_allocation_previews_cycle_created_idx
  ON public.observation_allocation_previews (cuatrimestre_id, created_at DESC);
CREATE INDEX observation_allocation_runs_cycle_initiated_idx
  ON public.observation_allocation_runs (cuatrimestre_id, initiated_at DESC);

ALTER TABLE public.observation_allocation_preferences ENABLE ROW LEVEL SECURITY;
