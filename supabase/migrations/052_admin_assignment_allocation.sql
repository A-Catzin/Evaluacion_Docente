BEFORE INSERT OR UPDATE ON public.observation_allocation_preferences
FOR EACH ROW EXECUTE FUNCTION public.validate_observation_allocation_preference();

CREATE OR REPLACE FUNCTION public.admin_assignment_teacher_candidates(
  p_cuatrimestre_id INTEGER, p_search TEXT DEFAULT '', p_include_all_active BOOLEAN DEFAULT false
)
RETURNS TABLE(docente_id INTEGER, nombre TEXT, apellidos TEXT, academic_activity BOOLEAN)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_search TEXT := left(trim(COALESCE(p_search, '')), 120);
BEGIN
  IF NOT public.audit_is_superadmin() OR p_cuatrimestre_id IS NULL OR p_cuatrimestre_id <= 0
    OR NOT EXISTS (SELECT 1 FROM public.cuatrimestres c WHERE c.id = p_cuatrimestre_id) THEN
    RAISE EXCEPTION 'superadmin and valid cycle required' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT d.id, d.nombre, d.apellidos,
    EXISTS (SELECT 1 FROM public.grupos g WHERE g.docente_id = d.id AND g.cuatrimestre_id = p_cuatrimestre_id AND g.activo IS TRUE)
  FROM public.docentes d
  WHERE d.activo IS TRUE
    AND (p_include_all_active OR EXISTS (
      SELECT 1 FROM public.grupos g WHERE g.docente_id = d.id AND g.cuatrimestre_id = p_cuatrimestre_id AND g.activo IS TRUE
    ))
    AND (v_search = '' OR concat_ws(' ', d.nombre, d.apellidos) ILIKE '%' || v_search || '%')
  ORDER BY d.apellidos, d.nombre, d.id
  LIMIT 500;
END;
$function$;

