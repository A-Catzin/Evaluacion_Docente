-- Normalized group schedules: a schedule belongs to an assigned group, which already
-- owns the cycle, subject, and teacher relationships.
CREATE TABLE public.horarios_grupo (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grupo_id INTEGER NOT NULL REFERENCES public.grupos(id) ON DELETE CASCADE,
  dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  aula TEXT CHECK (aula IS NULL OR length(btrim(aula)) BETWEEN 1 AND 120),
  activo BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (hora_inicio < hora_fin)
);

CREATE INDEX horarios_grupo_grupo_activo_idx
  ON public.horarios_grupo (grupo_id, dia_semana, hora_inicio)
  WHERE activo;
CREATE UNIQUE INDEX horarios_grupo_active_duplicate_idx
  ON public.horarios_grupo (grupo_id, dia_semana, hora_inicio, hora_fin)
  WHERE activo;

ALTER TABLE public.horarios_grupo ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.horarios_grupo FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.admin_save_horario_grupo(
  p_id BIGINT,
  p_cuatrimestre_id INTEGER,
  p_grupo_id INTEGER,
  p_dia_semana SMALLINT,
  p_hora_inicio TIME,
  p_hora_fin TIME,
  p_aula TEXT
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_id BIGINT; v_aula TEXT := NULLIF(btrim(p_aula), '');
BEGIN
  IF NOT public.audit_is_superadmin() THEN RAISE EXCEPTION 'superadmin required' USING ERRCODE = '42501'; END IF;
  IF p_cuatrimestre_id IS NULL OR p_cuatrimestre_id <= 0
    OR NOT EXISTS (SELECT 1 FROM public.cuatrimestres c WHERE c.id = p_cuatrimestre_id)
    OR p_grupo_id IS NULL OR p_grupo_id <= 0 OR p_dia_semana NOT BETWEEN 1 AND 7
    OR p_hora_inicio IS NULL OR p_hora_fin IS NULL OR p_hora_inicio >= p_hora_fin
    OR length(v_aula) > 120
    OR NOT EXISTS (SELECT 1 FROM public.grupos g WHERE g.id = p_grupo_id AND g.cuatrimestre_id = p_cuatrimestre_id AND g.activo = true) THEN
    RAISE EXCEPTION 'invalid group schedule' USING ERRCODE = '22023';
  END IF;
  IF p_id IS NULL THEN
    INSERT INTO public.horarios_grupo (grupo_id, dia_semana, hora_inicio, hora_fin, aula)
    VALUES (p_grupo_id, p_dia_semana, p_hora_inicio, p_hora_fin, v_aula)
    RETURNING id INTO v_id;
  ELSE
    UPDATE public.horarios_grupo AS h
    SET grupo_id = p_grupo_id, dia_semana = p_dia_semana, hora_inicio = p_hora_inicio,
      hora_fin = p_hora_fin, aula = v_aula, activo = true, updated_at = now()
    WHERE h.id = p_id
      AND EXISTS (
        SELECT 1 FROM public.grupos old_group
        WHERE old_group.id = h.grupo_id
          AND old_group.cuatrimestre_id = p_cuatrimestre_id
      )
    RETURNING h.id INTO v_id;
    IF v_id IS NULL THEN RAISE EXCEPTION 'schedule not found' USING ERRCODE = '22023'; END IF;
  END IF;
  RETURN jsonb_build_object('id', v_id);
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_deactivate_horario_grupo(p_id BIGINT, p_cuatrimestre_id INTEGER)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NOT public.audit_is_superadmin() OR p_id IS NULL OR p_id <= 0 OR p_cuatrimestre_id IS NULL OR p_cuatrimestre_id <= 0 THEN
    RAISE EXCEPTION 'superadmin and valid schedule required' USING ERRCODE = '42501';
  END IF;
  UPDATE public.horarios_grupo AS h
  SET activo = false, updated_at = now()
  WHERE h.id = p_id AND h.activo = true
    AND EXISTS (
      SELECT 1 FROM public.grupos g
      WHERE g.id = h.grupo_id AND g.cuatrimestre_id = p_cuatrimestre_id
    );
  IF NOT FOUND THEN RAISE EXCEPTION 'active schedule not found' USING ERRCODE = '22023'; END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_apply_horarios_grupo(
  p_cuatrimestre_id INTEGER,
  p_horarios JSONB
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_created INTEGER := 0; v_noop INTEGER := 0;
BEGIN
  IF NOT public.audit_is_superadmin() OR p_cuatrimestre_id IS NULL OR p_cuatrimestre_id <= 0
    OR p_horarios IS NULL OR jsonb_typeof(p_horarios) <> 'array' OR jsonb_array_length(p_horarios) > 1000
    OR NOT EXISTS (SELECT 1 FROM public.cuatrimestres WHERE id = p_cuatrimestre_id) THEN
    RAISE EXCEPTION 'invalid group schedule import' USING ERRCODE = '22023';
  END IF;
  PERFORM 1 FROM public.cuatrimestres WHERE id = p_cuatrimestre_id FOR UPDATE;
  CREATE TEMP TABLE import_horarios_grupo_stage ON COMMIT DROP AS
  SELECT e.ordinality::INTEGER AS ordinal, e.value->>'grupo_id' AS grupo_id_text,
    e.value->>'dia_semana' AS dia_semana_text, e.value->>'hora_inicio' AS hora_inicio_text,
    e.value->>'hora_fin' AS hora_fin_text, NULLIF(btrim(COALESCE(e.value->>'aula', '')), '') AS aula
  FROM jsonb_array_elements(p_horarios) WITH ORDINALITY AS e(value, ordinality);
  IF EXISTS (
    SELECT 1 FROM pg_temp.import_horarios_grupo_stage s
    WHERE s.grupo_id_text IS NULL OR s.grupo_id_text !~ '^[1-9][0-9]*$'
      OR s.dia_semana_text IS NULL OR s.dia_semana_text !~ '^[1-7]$'
      OR s.hora_inicio_text IS NULL OR s.hora_inicio_text !~ '^([01][0-9]|2[0-3]):[0-5][0-9](:[0-5][0-9])?$'
      OR s.hora_fin_text IS NULL OR s.hora_fin_text !~ '^([01][0-9]|2[0-3]):[0-5][0-9](:[0-5][0-9])?$'
      OR length(s.aula) > 120
  ) THEN RAISE EXCEPTION 'invalid group schedule import row' USING ERRCODE = '22023'; END IF;
  ALTER TABLE pg_temp.import_horarios_grupo_stage ADD COLUMN grupo_id INTEGER, ADD COLUMN dia_semana SMALLINT, ADD COLUMN hora_inicio TIME, ADD COLUMN hora_fin TIME;
  UPDATE pg_temp.import_horarios_grupo_stage
  SET grupo_id = grupo_id_text::INTEGER, dia_semana = dia_semana_text::SMALLINT,
    hora_inicio = hora_inicio_text::TIME, hora_fin = hora_fin_text::TIME;
  IF EXISTS (SELECT 1 FROM pg_temp.import_horarios_grupo_stage WHERE hora_inicio >= hora_fin)
    OR EXISTS (SELECT 1 FROM pg_temp.import_horarios_grupo_stage GROUP BY grupo_id, dia_semana, hora_inicio, hora_fin HAVING count(*) > 1)
    OR EXISTS (
      SELECT 1 FROM pg_temp.import_horarios_grupo_stage s
      LEFT JOIN public.grupos g ON g.id = s.grupo_id AND g.cuatrimestre_id = p_cuatrimestre_id AND g.activo = true
      WHERE g.id IS NULL
    ) THEN RAISE EXCEPTION 'unsafe group schedule import' USING ERRCODE = '22023'; END IF;
  SELECT count(*) INTO v_noop FROM pg_temp.import_horarios_grupo_stage s
  WHERE EXISTS (SELECT 1 FROM public.horarios_grupo h WHERE h.grupo_id = s.grupo_id AND h.dia_semana = s.dia_semana
    AND h.hora_inicio = s.hora_inicio AND h.hora_fin = s.hora_fin AND h.activo);
  INSERT INTO public.horarios_grupo (grupo_id, dia_semana, hora_inicio, hora_fin, aula)
  SELECT s.grupo_id, s.dia_semana, s.hora_inicio, s.hora_fin, s.aula
  FROM pg_temp.import_horarios_grupo_stage s
  WHERE NOT EXISTS (SELECT 1 FROM public.horarios_grupo h WHERE h.grupo_id = s.grupo_id AND h.dia_semana = s.dia_semana
    AND h.hora_inicio = s.hora_inicio AND h.hora_fin = s.hora_fin AND h.activo);
  GET DIAGNOSTICS v_created = ROW_COUNT;
  RETURN jsonb_build_object('created', v_created, 'noOp', v_noop);
END;
$function$;

-- The test-cycle deletion guard discovers dependencies from the live FK graph. Add
-- this child explicitly to its reviewed closure and delete it before grupos.
CREATE OR REPLACE FUNCTION public.test_cycle_assert_known_dependencies()
RETURNS VOID LANGUAGE plpgsql STABLE SET search_path TO '' AS $function$
DECLARE v_unknown TEXT; v_unscoped TEXT;
  v_allowed TEXT[] := ARRAY[
    'autodiagnostico_submission_windows', 'autodiagnosticos', 'autoevaluacion_docente', 'calificacion_final_docente', 'calificaciones_finales',
    'coordinador_docentes', 'coordinated_teacher_assignments', 'observation_teacher_assignments', 'teacher_assignment_backfill_review',
    'docente_360_feedback', 'docente_modalidad_historica', 'encuesta_control_envio', 'encuesta_estudiantil', 'encuesta_estudiantil_respuestas',
    'evaluacion_coordinacion', 'evaluacion_planeacion', 'grupos', 'horarios_grupo', 'import_issues', 'import_runs', 'inscripciones', 'institutional_notices',
    'instrument_submissions', 'instrument_answers', 'instrument_evidence', 'instrument_administrative_check_answers',
    'observation_allocation_preferences', 'observation_allocation_previews', 'observation_allocation_runs',
    'observacion_clase', 'observaciones', 'planeaciones', 'planning_group_document_status', 'planning_group_np', 'planning_subject_np', 'planning_submission_windows'
  ];
BEGIN
  WITH RECURSIVE dependencies(relid) AS (
    SELECT 'public.cuatrimestres'::regclass::oid UNION
    SELECT con.conrelid FROM pg_catalog.pg_constraint con JOIN dependencies d ON d.relid = con.confrelid WHERE con.contype = 'f'
  ), tables AS (
    SELECT DISTINCT c.oid, c.relname FROM dependencies d JOIN pg_catalog.pg_class c ON c.oid = d.relid
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relname <> 'cuatrimestres'
  ) SELECT string_agg(relname, ', ' ORDER BY relname) INTO v_unknown FROM tables WHERE NOT (relname = ANY(v_allowed));
  IF v_unknown IS NOT NULL THEN RAISE EXCEPTION 'test cycle dependency guard blocked deletion' USING ERRCODE = 'TC004'; END IF;
  WITH RECURSIVE dependencies(relid) AS (
    SELECT 'public.cuatrimestres'::regclass::oid UNION
    SELECT con.conrelid FROM pg_catalog.pg_constraint con JOIN dependencies d ON d.relid = con.confrelid WHERE con.contype = 'f'
  ) SELECT string_agg(c.relname, ', ' ORDER BY c.relname) INTO v_unscoped
    FROM dependencies d JOIN pg_catalog.pg_class c ON c.oid = d.relid JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relname <> 'cuatrimestres' AND public.test_cycle_scope_predicate(c.relname) IS NULL;
  IF v_unscoped IS NOT NULL THEN RAISE EXCEPTION 'test cycle dependency guard blocked deletion' USING ERRCODE = 'TC004'; END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.test_cycle_deletion_preview(p_cuatrimestre_id INTEGER)
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO '' AS $function$
DECLARE v_cycle public.cuatrimestres%ROWTYPE; v_table TEXT; v_counts JSONB := '{}'::jsonb;
  v_tables TEXT[] := ARRAY[
    'autodiagnostico_submission_windows', 'autodiagnosticos', 'autoevaluacion_docente', 'calificacion_final_docente', 'calificaciones_finales',
    'coordinador_docentes', 'coordinated_teacher_assignments', 'observation_teacher_assignments', 'teacher_assignment_backfill_review',
    'docente_360_feedback', 'docente_modalidad_historica', 'encuesta_control_envio', 'encuesta_estudiantil', 'encuesta_estudiantil_respuestas',
    'evaluacion_coordinacion', 'evaluacion_planeacion', 'grupos', 'horarios_grupo', 'import_issues', 'import_runs', 'inscripciones', 'institutional_notices',
    'instrument_submissions', 'instrument_answers', 'instrument_evidence', 'instrument_administrative_check_answers',
    'observation_allocation_preferences', 'observation_allocation_previews', 'observation_allocation_runs', 'observacion_clase', 'observaciones',
    'planeaciones', 'planning_group_document_status', 'planning_group_np', 'planning_subject_np', 'planning_submission_windows'
  ];
BEGIN
  IF NOT public.audit_is_superadmin() THEN RAISE EXCEPTION 'superadmin required' USING ERRCODE = '42501'; END IF;
  IF p_cuatrimestre_id IS NULL OR p_cuatrimestre_id <= 0 THEN RAISE EXCEPTION 'valid cycle required' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_cycle FROM public.cuatrimestres WHERE id = p_cuatrimestre_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'test cycle not found' USING ERRCODE = 'TC005'; END IF;
  PERFORM public.test_cycle_assert_deletable(v_cycle); PERFORM public.test_cycle_assert_known_dependencies();
  FOREACH v_table IN ARRAY v_tables LOOP
    IF to_regclass('public.' || v_table) IS NOT NULL THEN v_counts := v_counts || jsonb_build_object(v_table, public.test_cycle_count_rows(v_table, p_cuatrimestre_id)); END IF;
  END LOOP;
  RETURN jsonb_build_object('cycle_id', v_cycle.id, 'cycle_label', public.test_cycle_label(v_cycle), 'counts', v_counts,
    'audit_events_retained', true, 'storage_cleanup_pending', (SELECT count(*) FROM public.test_cycle_storage_cleanup s WHERE s.deleted_cycle_id = p_cuatrimestre_id AND s.status = 'pending'));
END;
$function$;

CREATE OR REPLACE FUNCTION public.delete_test_cycle(p_cuatrimestre_id INTEGER, p_confirmation TEXT)
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $function$
DECLARE v_cycle public.cuatrimestres%ROWTYPE; v_table TEXT; v_counts JSONB := '{}'::jsonb; v_role TEXT; v_audit_suppression_token UUID;
  v_tables TEXT[] := ARRAY[
    'autodiagnostico_submission_windows', 'autodiagnosticos', 'autoevaluacion_docente', 'calificacion_final_docente', 'calificaciones_finales',
    'coordinador_docentes', 'coordinated_teacher_assignments', 'observation_teacher_assignments', 'teacher_assignment_backfill_review',
    'docente_360_feedback', 'docente_modalidad_historica', 'encuesta_control_envio', 'encuesta_estudiantil', 'encuesta_estudiantil_respuestas',
    'evaluacion_coordinacion', 'evaluacion_planeacion', 'grupos', 'horarios_grupo', 'import_issues', 'import_runs', 'inscripciones', 'institutional_notices',
    'instrument_submissions', 'instrument_answers', 'instrument_evidence', 'instrument_administrative_check_answers',
    'observation_allocation_preferences', 'observation_allocation_previews', 'observation_allocation_runs', 'observacion_clase', 'observaciones',
    'planeaciones', 'planning_group_document_status', 'planning_group_np', 'planning_subject_np', 'planning_submission_windows'
  ];
BEGIN
  IF NOT public.audit_is_superadmin() THEN RAISE EXCEPTION 'superadmin required' USING ERRCODE = '42501'; END IF;
  IF p_cuatrimestre_id IS NULL OR p_cuatrimestre_id <= 0 THEN RAISE EXCEPTION 'valid cycle required' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_cycle FROM public.cuatrimestres WHERE id = p_cuatrimestre_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'test cycle not found' USING ERRCODE = 'TC005'; END IF;
  PERFORM public.test_cycle_assert_deletable(v_cycle, p_confirmation); PERFORM public.test_cycle_assert_known_dependencies();
  IF to_regclass('public.planeaciones') IS NOT NULL THEN
    INSERT INTO public.test_cycle_storage_cleanup (deleted_cycle_id, cycle_label, bucket, object_reference, reference_kind)
    SELECT v_cycle.id, public.test_cycle_label(v_cycle), 'planeaciones', p.url_pdf, 'url'
    FROM public.planeaciones p
    WHERE p.cuatrimestre_id = v_cycle.id AND NULLIF(trim(COALESCE(p.url_pdf, '')), '') IS NOT NULL
    ON CONFLICT (deleted_cycle_id, bucket, object_reference) DO NOTHING;
  END IF;
  IF to_regclass('public.institutional_notices') IS NOT NULL THEN
    INSERT INTO public.test_cycle_storage_cleanup (deleted_cycle_id, cycle_label, bucket, object_reference, reference_kind)
    SELECT v_cycle.id, public.test_cycle_label(v_cycle), 'avisos', n.image_path, 'path'
    FROM public.institutional_notices n
    WHERE n.cuatrimestre_id = v_cycle.id AND n.image_path IS NOT NULL
    ON CONFLICT (deleted_cycle_id, bucket, object_reference) DO NOTHING;
  END IF;
  FOREACH v_table IN ARRAY v_tables LOOP
    IF to_regclass('public.' || v_table) IS NOT NULL THEN v_counts := v_counts || jsonb_build_object(v_table, public.test_cycle_count_rows(v_table, v_cycle.id)); END IF;
  END LOOP;
  SELECT u.rol INTO v_role FROM public.usuarios u WHERE u.id = auth.uid();
  PERFORM public.audit_write_event(auth.uid(), v_role, 'admin.test_cycle', 'test_cycle.deleted', NULL, 'cuatrimestres',
    jsonb_build_object('cycle_id', v_cycle.id), 'delete', '[]'::jsonb, '{}'::jsonb, '{}'::jsonb,
    jsonb_build_object('cycle_id', v_cycle.id, 'cycle_label', public.test_cycle_label(v_cycle), 'operational_counts', v_counts, 'audit_events_retained', true));
  v_audit_suppression_token := extensions.gen_random_uuid();
  PERFORM set_config('app.private_test_cycle_delete_audit_token', v_audit_suppression_token::TEXT, true);
  INSERT INTO public.test_cycle_audit_suppression_context (transaction_id, backend_pid, actor_id, token)
  VALUES (txid_current(), pg_backend_pid(), auth.uid(), v_audit_suppression_token);
  FOREACH v_table IN ARRAY ARRAY[
    'import_issues', 'encuesta_estudiantil_respuestas', 'encuesta_control_envio', 'encuesta_estudiantil', 'evaluacion_planeacion', 'observacion_clase',
    'autoevaluacion_docente', 'instrument_administrative_check_answers', 'instrument_answers', 'instrument_evidence', 'instrument_submissions',
    'observation_allocation_preferences', 'observation_allocation_runs', 'observation_allocation_previews', 'planning_subject_np',
    'planning_group_document_status', 'planning_group_np', 'evaluacion_coordinacion', 'observaciones', 'planeaciones', 'planning_submission_windows',
    'autodiagnostico_submission_windows', 'autodiagnosticos', 'docente_360_feedback', 'calificacion_final_docente', 'calificaciones_finales',
    'docente_modalidad_historica', 'institutional_notices', 'inscripciones', 'teacher_assignment_backfill_review', 'coordinated_teacher_assignments',
    'observation_teacher_assignments', 'coordinador_docentes', 'import_runs', 'horarios_grupo', 'grupos'
  ] LOOP
    IF to_regclass('public.' || v_table) IS NOT NULL THEN PERFORM public.test_cycle_delete_rows(v_table, v_cycle.id); END IF;
  END LOOP;
  DELETE FROM public.cuatrimestres WHERE id = v_cycle.id;
  DELETE FROM public.test_cycle_audit_suppression_context WHERE transaction_id = txid_current() AND backend_pid = pg_backend_pid() AND actor_id = auth.uid() AND token = v_audit_suppression_token;
  PERFORM set_config('app.private_test_cycle_delete_audit_token', '', true);
  PERFORM public.refrescar_resultados_agregados();
  RETURN jsonb_build_object('cycle_id', v_cycle.id, 'cycle_label', public.test_cycle_label(v_cycle), 'counts', v_counts,
    'audit_events_retained', true, 'storage_cleanup_pending', (SELECT count(*) FROM public.test_cycle_storage_cleanup s WHERE s.deleted_cycle_id = v_cycle.id AND s.status = 'pending'));
END;
$function$;

