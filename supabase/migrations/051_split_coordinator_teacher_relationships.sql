  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_actor_id UUID NOT NULL REFERENCES public.usuarios(id),
  docente_id INTEGER NOT NULL REFERENCES public.docentes(id),
  cuatrimestre_id INTEGER NOT NULL REFERENCES public.cuatrimestres(id),
  target_assignment_type TEXT CHECK (target_assignment_type IN ('coordinated', 'observation')),
  status TEXT NOT NULL CHECK (status IN ('backfilled', 'needs_review')),
  reason_code TEXT NOT NULL CHECK (reason_code IN ('coordinator', 'observer', 'inactive_actor', 'inactive_teacher', 'unsupported_role')),
  reviewed_at TIMESTAMPTZ,
  reviewed_by UUID REFERENCES public.usuarios(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (legacy_actor_id, docente_id, cuatrimestre_id)
