  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  coordinador_id UUID NOT NULL REFERENCES public.usuarios(id),
  docente_id INTEGER NOT NULL REFERENCES public.docentes(id),
