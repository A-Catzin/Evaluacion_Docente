CREATE OR REPLACE FUNCTION public.validate_teacher_assignment_actor()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_actor_id UUID;
  v_role TEXT;
  v_active BOOLEAN;
BEGIN
  v_actor_id := CASE WHEN TG_TABLE_NAME = 'coordinated_teacher_assignments' THEN NEW.coordinador_id ELSE NEW.evaluator_id END;
  SELECT u.rol, COALESCE(u.activo, true) INTO v_role, v_active FROM public.usuarios u WHERE u.id = v_actor_id;
  IF NOT FOUND OR NOT v_active
    OR (TG_TABLE_NAME = 'coordinated_teacher_assignments' AND v_role <> 'coordinador')
    OR (TG_TABLE_NAME = 'observation_teacher_assignments' AND v_role NOT IN ('coordinador', 'observador')) THEN
    RAISE EXCEPTION 'active actor with an allowed role required' USING ERRCODE = '42501';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.docentes d WHERE d.id = NEW.docente_id) THEN
    RAISE EXCEPTION 'teacher required' USING ERRCODE = '42501';
  END IF;
  IF TG_OP = 'UPDATE' AND (
    NEW.docente_id IS DISTINCT FROM OLD.docente_id OR NEW.cuatrimestre_id IS DISTINCT FROM OLD.cuatrimestre_id
    OR v_actor_id IS DISTINCT FROM CASE WHEN TG_TABLE_NAME = 'coordinated_teacher_assignments' THEN OLD.coordinador_id ELSE OLD.evaluator_id END
    OR NEW.assigned_at IS DISTINCT FROM OLD.assigned_at OR NEW.assigned_by IS DISTINCT FROM OLD.assigned_by
    OR NEW.source IS DISTINCT FROM OLD.source
  ) THEN
    RAISE EXCEPTION 'assignment identity is immutable' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$function$;

CREATE TRIGGER validate_coordinated_teacher_assignment_actor
BEFORE INSERT OR UPDATE ON public.coordinated_teacher_assignments
FOR EACH ROW EXECUTE FUNCTION public.validate_teacher_assignment_actor();
CREATE TRIGGER validate_observation_teacher_assignment_actor
BEFORE INSERT OR UPDATE ON public.observation_teacher_assignments
FOR EACH ROW EXECUTE FUNCTION public.validate_teacher_assignment_actor();

