  PERFORM public.test_cycle_delete_rows('import_issues', v_cycle.id); PERFORM public.test_cycle_delete_rows('encuesta_estudiantil_respuestas', v_cycle.id); PERFORM public.test_cycle_delete_rows('encuesta_control_envio', v_cycle.id); IF to_regclass('public.encuesta_estudiantil') IS NOT NULL THEN PERFORM public.test_cycle_delete_rows('encuesta_estudiantil', v_cycle.id); END IF;
  PERFORM public.test_cycle_delete_rows('evaluacion_planeacion', v_cycle.id); PERFORM public.test_cycle_delete_rows('observacion_clase', v_cycle.id); PERFORM public.test_cycle_delete_rows('autoevaluacion_docente', v_cycle.id); PERFORM public.test_cycle_delete_rows('evaluacion_coordinacion', v_cycle.id); PERFORM public.test_cycle_delete_rows('observaciones', v_cycle.id); PERFORM public.test_cycle_delete_rows('planeaciones', v_cycle.id); PERFORM public.test_cycle_delete_rows('planning_submission_windows', v_cycle.id); PERFORM public.test_cycle_delete_rows('autodiagnosticos', v_cycle.id); PERFORM public.test_cycle_delete_rows('docente_360_feedback', v_cycle.id); IF to_regclass('public.calificacion_final_docente') IS NOT NULL THEN PERFORM public.test_cycle_delete_rows('calificacion_final_docente', v_cycle.id); END IF; PERFORM public.test_cycle_delete_rows('calificaciones_finales', v_cycle.id); IF to_regclass('public.docente_modalidad_historica') IS NOT NULL THEN PERFORM public.test_cycle_delete_rows('docente_modalidad_historica', v_cycle.id); END IF; PERFORM public.test_cycle_delete_rows('institutional_notices', v_cycle.id); PERFORM public.test_cycle_delete_rows('inscripciones', v_cycle.id); PERFORM public.test_cycle_delete_rows('teacher_assignment_backfill_review', v_cycle.id); PERFORM public.test_cycle_delete_rows('coordinated_teacher_assignments', v_cycle.id); PERFORM public.test_cycle_delete_rows('observation_teacher_assignments', v_cycle.id); PERFORM public.test_cycle_delete_rows('coordinador_docentes', v_cycle.id); PERFORM public.test_cycle_delete_rows('import_runs', v_cycle.id); PERFORM public.test_cycle_delete_rows('grupos', v_cycle.id);
