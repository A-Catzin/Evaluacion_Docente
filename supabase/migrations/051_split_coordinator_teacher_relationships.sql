CREATE OR REPLACE FUNCTION public.replace_teacher_assignments(
  p_assignment_type TEXT, p_actor_id UUID, p_cuatrimestre_id INTEGER, p_docente_ids INTEGER[]
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_role TEXT; v_ids INTEGER[]; v_added INTEGER; v_revoked INTEGER;
BEGIN
  -- A PostgREST RPC invocation runs this replace, its revocations, and its audit
  -- event in one database transaction; any validation failure rolls all back.
  IF NOT public.audit_is_superadmin() OR p_assignment_type NOT IN ('coordinated', 'observation')
    OR p_actor_id IS NULL OR p_cuatrimestre_id IS NULL OR p_cuatrimestre_id <= 0 OR p_docente_ids IS NULL
    OR NOT EXISTS (SELECT 1 FROM public.cuatrimestres c WHERE c.id = p_cuatrimestre_id) THEN
    RAISE EXCEPTION 'invalid teacher assignment request' USING ERRCODE = '22023';
  END IF;
  SELECT u.rol INTO v_role FROM public.usuarios u WHERE u.id = p_actor_id AND COALESCE(u.activo, true);
  IF NOT FOUND OR (p_assignment_type = 'coordinated' AND v_role <> 'coordinador')
    OR (p_assignment_type = 'observation' AND v_role NOT IN ('coordinador', 'observador')) THEN
    RAISE EXCEPTION 'actor role is not eligible for assignment type' USING ERRCODE = '42501';
  END IF;
  SELECT COALESCE(array_agg(DISTINCT x), ARRAY[]::INTEGER[]) INTO v_ids FROM unnest(p_docente_ids) AS x WHERE x > 0;
  IF cardinality(v_ids) <> cardinality(p_docente_ids) OR EXISTS (
    SELECT 1 FROM unnest(v_ids) x WHERE NOT EXISTS (SELECT 1 FROM public.docentes d WHERE d.id = x)
  ) THEN RAISE EXCEPTION 'unique teacher ids required' USING ERRCODE = '22023'; END IF;

  IF p_assignment_type = 'coordinated' THEN
    UPDATE public.coordinated_teacher_assignments SET revoked_at = now(), revoked_by = auth.uid()
      WHERE coordinador_id = p_actor_id AND cuatrimestre_id = p_cuatrimestre_id AND revoked_at IS NULL AND NOT (docente_id = ANY(v_ids));
    GET DIAGNOSTICS v_revoked = ROW_COUNT;
    UPDATE public.coordinated_teacher_assignments SET revoked_at = NULL, revoked_by = NULL
      WHERE coordinador_id = p_actor_id AND cuatrimestre_id = p_cuatrimestre_id AND revoked_at IS NOT NULL AND docente_id = ANY(v_ids);
    INSERT INTO public.coordinated_teacher_assignments (coordinador_id, docente_id, cuatrimestre_id, assigned_by)
      SELECT p_actor_id, x, p_cuatrimestre_id, auth.uid() FROM unnest(v_ids) x
      WHERE NOT EXISTS (SELECT 1 FROM public.coordinated_teacher_assignments a WHERE a.coordinador_id = p_actor_id AND a.docente_id = x AND a.cuatrimestre_id = p_cuatrimestre_id);
    GET DIAGNOSTICS v_added = ROW_COUNT;
  ELSE
    UPDATE public.observation_teacher_assignments SET revoked_at = now(), revoked_by = auth.uid()
      WHERE evaluator_id = p_actor_id AND cuatrimestre_id = p_cuatrimestre_id AND revoked_at IS NULL AND NOT (docente_id = ANY(v_ids));
    GET DIAGNOSTICS v_revoked = ROW_COUNT;
    UPDATE public.observation_teacher_assignments SET revoked_at = NULL, revoked_by = NULL
      WHERE evaluator_id = p_actor_id AND cuatrimestre_id = p_cuatrimestre_id AND revoked_at IS NOT NULL AND docente_id = ANY(v_ids);
    INSERT INTO public.observation_teacher_assignments (evaluator_id, docente_id, cuatrimestre_id, assigned_by)
      SELECT p_actor_id, x, p_cuatrimestre_id, auth.uid() FROM unnest(v_ids) x
      WHERE NOT EXISTS (SELECT 1 FROM public.observation_teacher_assignments a WHERE a.evaluator_id = p_actor_id AND a.docente_id = x AND a.cuatrimestre_id = p_cuatrimestre_id);
    GET DIAGNOSTICS v_added = ROW_COUNT;
  END IF;
  PERFORM public.audit_write_event(auth.uid(), 'superadmin', 'admin.assignment', 'teacher_assignment.replaced', NULL,
    'teacher_assignments', jsonb_build_object('actor_id', p_actor_id, 'cuatrimestre_id', p_cuatrimestre_id, 'assignment_type', p_assignment_type),
    'replace', '[]'::jsonb, '{}'::jsonb, '{}'::jsonb,
    jsonb_build_object('assignment_type', p_assignment_type, 'cuatrimestre_id', p_cuatrimestre_id, 'requested_count', cardinality(v_ids), 'inserted_count', v_added, 'revoked_count', v_revoked));
  RETURN cardinality(v_ids);
END;
$function$;

-- Backfill only active, role-eligible actors. A coordinator gets
-- coordination scope only; it never receives observation scope from legacy data.
INSERT INTO public.teacher_assignment_backfill_review (
  legacy_actor_id, docente_id, cuatrimestre_id, target_assignment_type, status, reason_code
)
SELECT cd.coordinador_id, cd.docente_id, cd.cuatrimestre_id,
  CASE WHEN u.rol = 'coordinador' THEN 'coordinated' WHEN u.rol = 'observador' THEN 'observation' END,
  CASE WHEN u.rol IN ('coordinador', 'observador') AND COALESCE(u.activo, true) THEN 'backfilled' ELSE 'needs_review' END,
  CASE WHEN u.rol = 'coordinador' THEN 'coordinator' WHEN u.rol = 'observador' THEN 'observer'
    WHEN NOT COALESCE(u.activo, true) THEN 'inactive_actor' ELSE 'unsupported_role' END
FROM public.coordinador_docentes cd
JOIN public.usuarios u ON u.id = cd.coordinador_id
JOIN public.docentes d ON d.id = cd.docente_id
WHERE cd.cuatrimestre_id IS NOT NULL
ON CONFLICT (legacy_actor_id, docente_id, cuatrimestre_id) DO NOTHING;

INSERT INTO public.coordinated_teacher_assignments (coordinador_id, docente_id, cuatrimestre_id, source)
SELECT r.legacy_actor_id, r.docente_id, r.cuatrimestre_id, 'legacy_backfill'
FROM public.teacher_assignment_backfill_review r
WHERE r.target_assignment_type = 'coordinated' AND r.status = 'backfilled'
ON CONFLICT (coordinador_id, docente_id, cuatrimestre_id) WHERE revoked_at IS NULL DO NOTHING;

INSERT INTO public.observation_teacher_assignments (evaluator_id, docente_id, cuatrimestre_id, source)
SELECT r.legacy_actor_id, r.docente_id, r.cuatrimestre_id, 'legacy_backfill'
FROM public.teacher_assignment_backfill_review r
WHERE r.target_assignment_type = 'observation' AND r.status = 'backfilled'
ON CONFLICT (evaluator_id, docente_id, cuatrimestre_id) WHERE revoked_at IS NULL DO NOTHING;

CREATE OR REPLACE FUNCTION public.enforce_staff_assignment_authorization()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_role TEXT; v_docente_id INTEGER; v_cycle_id INTEGER;
BEGIN
  SELECT u.rol INTO v_role FROM public.usuarios u WHERE u.id = auth.uid() AND COALESCE(u.activo, true);
  IF v_role IS NULL OR v_role = 'superadmin' THEN RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END; END IF;
  v_docente_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.docente_id ELSE NEW.docente_id END;
  v_cycle_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.cuatrimestre_id ELSE NEW.cuatrimestre_id END;
  IF TG_TABLE_NAME = 'observaciones' AND NOT public.can_observe_assigned_teacher(v_docente_id, v_cycle_id) THEN
    RAISE EXCEPTION 'observation assignment required' USING ERRCODE = '42501';
  END IF;
  IF TG_TABLE_NAME = 'evaluacion_coordinacion' AND NOT public.can_manage_coordinated_teacher(v_docente_id, v_cycle_id) THEN
    RAISE EXCEPTION 'coordinated teacher assignment required' USING ERRCODE = '42501';
  END IF;
  IF TG_TABLE_NAME = 'planeaciones' AND v_role = 'coordinador'
    AND TG_OP = 'UPDATE' AND NEW.fecha_evaluacion IS DISTINCT FROM OLD.fecha_evaluacion
    AND NOT public.can_manage_coordinated_teacher(v_docente_id, v_cycle_id) THEN
    RAISE EXCEPTION 'coordinated teacher assignment required' USING ERRCODE = '42501';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$function$;

